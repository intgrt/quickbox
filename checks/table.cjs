const {JSDOM, VirtualConsole} = require('jsdom');
const {readFileSync, writeFileSync, mkdirSync} = require('node:fs');
const assert = require('node:assert/strict');
const vm = require('node:vm');
const dom = new JSDOM(readFileSync('index.html', 'utf8'), {url:'http://127.0.0.1:5174/', runScripts:'outside-only', pretendToBeVisual:true, virtualConsole:new VirtualConsole()});
const w = dom.window;
w.alert = message => { throw new Error(message); };
w.confirm = () => true;
w.fetch = async url => ({ok:true, json:async () => JSON.parse(readFileSync(String(url), 'utf8'))});
w.CSS = {supports:() => true};
for (const name of ['document-model.js', 'export-runtime.js', 'app.js']) vm.runInContext(readFileSync(name, 'utf8'), dom.getInternalVMContext(), {filename:name});
const data = () => w.captureSnapshot();
const table = () => data().pages[0].boxes[0];
const cell = () => w.document.querySelector('.table-cell');
const action = name => w.document.querySelector(`[data-action="${name}"]`).click();
const tick = () => new Promise(resolve => setTimeout(resolve, 10));
async function main() {
  for (let i = 0; i < 100 && !w.eval('documentReady'); i++) await tick();
  assert.ok(w.eval('documentReady'));
  w.document.getElementById('addTableBtn').click();
  assert.equal(table().cells.length, 3);
  assert.equal(table().cells[0].length, 3);
  const dragColumn = (distance, returnToStart = false) => {
    w.document.querySelector('.qb-table').getBoundingClientRect = () => ({width:444, height:114, left:0});
    w.document.querySelector('.table-column-resize').dispatchEvent(new w.MouseEvent('mousedown', {bubbles:true, button:0, clientX:148}));
    if (distance) w.document.dispatchEvent(new w.MouseEvent('mousemove', {clientX:148 + distance}));
    if (returnToStart) w.document.dispatchEvent(new w.MouseEvent('mousemove', {clientX:148}));
    w.document.dispatchEvent(new w.MouseEvent('mouseup'));
  };
  const historyBeforeDrag = w.eval('undoHistory.past.length');
  dragColumn(0);
  assert.equal(w.eval('undoHistory.past.length'), historyBeforeDrag, 'Clicking a divider must not create undo history');
  dragColumn(74);
  assert.deepEqual(Array.from(table().columnWidths), [1.5, .5, 1]);
  assert.equal(table().width, 450);
  assert.equal(w.eval('undoHistory.past.length'), historyBeforeDrag + 1);
  w.performUndo(); assert.equal(table().columnWidths, undefined);
  w.performRedo(); assert.deepEqual(Array.from(table().columnWidths), [1.5, .5, 1]);
  dragColumn(10000);
  assert.ok(table().columnWidths[1] / 3 * 444 >= 32 - 0.001, 'Adjacent column cannot collapse');
  w.performUndo();
  const historyBeforeRoundTrip = w.eval('undoHistory.past.length');
  dragColumn(30, true);
  assert.equal(w.eval('undoHistory.past.length'), historyBeforeRoundTrip);
  cell().dispatchEvent(new w.MouseEvent('click', {bubbles:true}));
  assert.equal(cell().contentEditable, 'plaintext-only', 'A single click must enable cell editing');
  assert.equal(w.document.activeElement, cell());
  cell().textContent = '<img src=x onerror=alert(1)> & Product';
  cell().dispatchEvent(new w.Event('input', {bubbles:true}));
  cell().blur();
  assert.equal(table().cells[0][0], '<img src=x onerror=alert(1)> & Product');
  w.performUndo(); assert.equal(table().cells[0][0], '');
  w.performRedo(); assert.ok(table().cells[0][0].includes('Product'));
  cell().focus(); action('row-above');
  assert.equal(table().cells.length, 4);
  assert.ok(table().cells[1][0].includes('Product'));
  action('column-left');
  assert.equal(table().cells[0].length, 4);
  assert.deepEqual(Array.from(table().columnWidths), [.75, .75, .5, 1]);
  assert.ok(table().cells[1][1].includes('Product'));
  action('delete-row'); action('delete-column');
  assert.deepEqual(Array.from(table().columnWidths), [1.5, .5, 1]);
  assert.ok(table().cells[0][0].includes('Product'));
  const previousCell = cell(); previousCell.focus();
  w.performUndo(); assert.equal(table().cells[0].length, 4);
  previousCell.dispatchEvent(new w.FocusEvent('blur'));
  w.performRedo(); assert.equal(table().cells[0].length, 3);
  for (let i=0; i<4; i++) { action('delete-row'); action('delete-column'); }
  assert.equal(table().cells.length, 1); assert.equal(table().cells[0].length, 1);
  assert.ok(w.document.querySelector('[data-action="delete-row"]').disabled);
  assert.ok(w.document.querySelector('[data-action="delete-column"]').disabled);
  action('row-below'); action('column-right');
  assert.equal(table().cells.length, 2); assert.equal(table().cells[0].length, 2);
  w.eval('getCurrentPage().boxes[0].cells = [["Product", "Notes"], ["Sample item", "<img src=x onerror=alert(1)> & a long plain-text note that wraps across several lines."]]; getCurrentPage().boxes[0].columnWidths = [1, 3]');
  w.renderCurrentPage();
  let saved;
  w.showSaveFilePicker = async () => ({name:'table.json', createWritable:async () => ({write:async value => {saved=value;}, close:async()=>{}})});
  await w.saveFile();
  w.addBox('button');
  w.openFile({target:{files:[new w.File([saved], 'table.json', {type:'application/json'})]}});
  for (let i=0; i<100 && data().pages[0].boxes.length !== 1; i++) await tick();
  assert.equal(data().pages[0].boxes.length, 1);
  assert.deepEqual(JSON.parse(JSON.stringify(table().cells)), JSON.parse(saved).pages[0].boxes[0].cells);
  assert.deepEqual(Array.from(table().columnWidths), [1, 3]);
  assert.equal(w.hasUnsavedChanges(), false);
  const document = JSON.parse(JSON.stringify(data()));
  assert.deepEqual(JSON.parse(JSON.stringify(w.eval('QuickBoxDocument').normalize(document).pages[0].boxes[0].cells)), document.pages[0].boxes[0].cells);
  for (const cells of [[], [[]], [['one'], []], [[{}]], Array.from({length:101}, () => [''])]) {
    const invalid = structuredClone(document); invalid.pages[0].boxes[0].cells = cells;
    assert.throws(() => w.eval('QuickBoxDocument').normalize(invalid));
  }
  for (const widths of [null, [], [1], [1, 0], [-1, 1], [1, Infinity], ['25%', 1]]) {
    const invalid = structuredClone(document); invalid.pages[0].boxes[0].columnWidths = widths;
    assert.throws(() => w.eval('QuickBoxDocument').normalize(invalid));
  }
  w.duplicateBox(w.eval('getCurrentPage().boxes[0]'));
  w.eval('getCurrentPage().boxes[1].cells[0][0] = "Independent copy"');
  assert.notEqual(data().pages[0].boxes[0].cells[0][0], data().pages[0].boxes[1].cells[0][0]);
  w.selectBox(w.eval('getCurrentPage().boxes[0]'));
  w.copyBox(); w.pasteBox();
  assert.equal(data().pages[0].boxes.length, 3);
  assert.deepEqual(JSON.parse(JSON.stringify(data().pages[0].boxes[2].cells)), document.pages[0].boxes[0].cells);
  assert.deepEqual(Array.from(data().pages[0].boxes[2].columnWidths), [1, 3]);
  w.eval('state.tempGroup = [...getCurrentPage().boxes]');
  w.prompt = () => 'Table modal';
  w.createModal();
  assert.equal(data().pages[1].boxes.length, 3);
  assert.equal(w.document.querySelectorAll('.qb-table').length, 3);
  const modalExport = new JSDOM(await w.generateExportHTML({}));
  assert.equal(modalExport.window.document.querySelectorAll('dialog .qb-table').length, 3);
  w.setMode('navigate');
  assert.equal(w.document.querySelectorAll('.table-controls, .table-cell, [contenteditable="plaintext-only"]').length, 0);
  const html = await w.generateExportHTML({}, document);
  const exported = new JSDOM(html);
  assert.equal(exported.window.document.querySelectorAll('.qb-table').length, 1);
  assert.deepEqual([...exported.window.document.querySelectorAll('.qb-table col')].map(col => col.style.width), ['25%', '75%']);
  assert.equal(exported.window.document.querySelectorAll('.table-column-resize').length, 0);
  assert.equal(exported.window.document.querySelectorAll('.qb-table img, .qb-table script, .table-controls, [contenteditable]').length, 0);
  assert.equal(exported.window.document.querySelector('.qb-table td').textContent, document.pages[0].boxes[0].cells[0][0]);
  mkdirSync('checks/output', {recursive:true});
  writeFileSync('checks/output/table-export.html', html);
  writeFileSync('checks/output/table.json', JSON.stringify(document, null, 2));
  console.log('Table checks passed: creation, cell edit undo/redo, column border drag/undo/redo/minimum/no-op, row/column insertion and deletion, width validation/persistence, Save/Open round-trip, independent duplication, copy/paste, grouped modal creation, Navigate mode, escaped page/modal export.');
  w.close();
}
main().catch(error => {console.error(error); process.exitCode = 1; w.close();});
